package main

import (
	"bytes"
	"crypto/hkdf"
	"crypto/sha256"
	"errors"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"github.com/genshinsim/gcsim/pkg/sharekey"
)

const outFile = "pkg/sharekey/key_embedded.go"

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	src, err := generate(os.Getenv("GCSIM_SHARE_KEY"))
	if err != nil {
		return err
	}
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	path := filepath.Join(root, outFile)
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, src) {
		return nil
	}
	return os.WriteFile(path, src, 0o644)
}

func generate(s string) ([]byte, error) {
	id, class, raw, err := sharekey.ParseRaw(s)
	if err != nil {
		return nil, err
	}
	defer clear(raw)
	stream, err := hkdf.Expand(sha256.New, raw, "sharekeygen", 2*sharekey.Size)
	if err != nil {
		return nil, err
	}
	k, err := sharekey.Split(id, class, raw, bytes.NewReader(stream))
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by sharekeygen. DO NOT EDIT.\n\n//go:build sharekey\n\npackage sharekey\n\n")
	fmt.Fprintf(&b, "var embedded = &Key{\n\tID: %q,\n\tClass: %q,\n\tparts: [][]byte{\n", k.ID, k.Class)
	for _, p := range k.Parts() {
		b.WriteString("\t\t{")
		for i, c := range p {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "0x%02x", c)
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t},\n}\n")
	return format.Source(b.Bytes())
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found")
		}
		dir = parent
	}
}
